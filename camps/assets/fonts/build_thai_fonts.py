"""Builds the PDF-ready Sarabun fonts + shaping tables used by assets/thai-shape.js.
jsPDF cannot apply OpenType GSUB, so Thai vowels / tone marks stack on top of each other. We copy Sarabun,
map its contextual glyph variants (.narrow, .small, .short, nikhahit+tone ligatures) to private-use code points,
and ship a tiny GSUB interpreter (thai-shape.js) that picks the right variant before text reaches jsPDF.
Run: python3 build_thai_fonts.py  (needs fonttools). Source fonts: ../../aka/fonts/Sarabun-*.ttf"""
import json, os
from fontTools.ttLib import TTFont
HERE = os.path.dirname(os.path.abspath(__file__)); SRC = os.path.join(HERE, '..', '..', 'aka', 'fonts')
reg = TTFont(os.path.join(SRC, 'Sarabun-Regular.ttf')); gs = reg['GSUB'].table; LL = gs.LookupList.Lookup
USED = [3, 4, 5, 16, 17, 18, 19, 20]
def cov(c): return list(c.glyphs)
look = {}
for i in USED:
    l = LL[i]; subs = []
    for st in l.SubTable:
        n = type(st).__name__
        if n == 'SingleSubst': subs.append({'t': 1, 'm': st.mapping})
        elif n == 'MultipleSubst': subs.append({'t': 2, 'm': st.mapping})
        elif n == 'LigatureSubst': subs.append({'t': 4, 'm': {k: [[x.Component, x.LigGlyph] for x in v] for k, v in st.ligatures.items()}})
        elif n == 'ChainContextSubst' and st.Format == 3:
            subs.append({'t': 6, 'b': [cov(c) for c in st.BacktrackCoverage], 'i': [cov(c) for c in st.InputCoverage], 'a': [cov(c) for c in st.LookAheadCoverage], 'r': [[r.SequenceIndex, r.LookupListIndex] for r in st.SubstLookupRecord]})
        else: raise SystemExit('unsupported subtable ' + n)
    look[i] = subs
# glyph names that can appear in the output and are not directly encoded
extra = set()
for i in USED:
    for s in look[i]:
        if s['t'] == 1: extra.update(s['m'].values())
        if s['t'] == 2: [extra.update(v) for v in s['m'].values()]
        if s['t'] == 4: [extra.add(lg) for v in s['m'].values() for _, lg in v]
cmap = reg.getBestCmap(); inv = {}
for cp, name in cmap.items(): inv.setdefault(name, cp)
pua = {}; nxt = 0xF700
for name in sorted(extra):
    if name in inv and 0x0E00 <= inv[name] <= 0x0E7F: continue
    if name not in reg.getGlyphOrder(): continue
    pua[name] = nxt; nxt += 1
thai = {cp: n for cp, n in cmap.items() if 0x0E00 <= cp <= 0x0E7F}
out = {}
for style in ('Regular', 'Bold'):
    f = TTFont(os.path.join(SRC, 'Sarabun-%s.ttf' % style)); order = set(f.getGlyphOrder())
    assert all(n in order for n in pua), 'missing glyph in ' + style
    for t in f['cmap'].tables:
        if t.isUnicode():
            for n, cp in pua.items(): t.cmap[cp] = n
    f.save(os.path.join(HERE, 'SarabunTH-%s.ttf' % style))
data = {'thai': {str(cp): n for cp, n in thai.items()}, 'pua': pua, 'order': [3, 4, 5], 'look': {str(k): v for k, v in look.items()}}
js = '/* generated by assets/fonts/build_thai_fonts.py */\n(function(g){\nvar D=' + json.dumps(data, separators=(',', ':')) + ';\n' + open(os.path.join(HERE, 'shape-core.js')).read() + '\n})(typeof window!=="undefined"?window:globalThis);\n'
open(os.path.join(HERE, '..', 'thai-shape.js'), 'w').write(js)
print('pua glyphs', len(pua))
